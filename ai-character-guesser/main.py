def question_process():
    possible_characters = list(current_characters.keys())
    asked_questions = []

    print("\nAnswer with Y for Yes, N for No, or ? if you are not sure.")

    while len(possible_characters) > 1:
        best_question = ""
        best_difference = len(possible_characters)

        for question in current_questions:
            if question not in asked_questions:
                yes_count = 0
                no_count = 0

                for character in possible_characters:
                    if current_characters[character][question] == True:
                        yes_count = yes_count + 1
                    else:
                        no_count = no_count + 1

                if yes_count > 0 and no_count > 0:
                    difference = abs(yes_count - no_count)

                    if difference < best_difference:
                        best_difference = difference
                        best_question = question

        if best_question == "":
            break

        asked_questions.append(best_question)

        while True:
            answer = input(current_questions[best_question]).strip().lower()

            if answer == "y" or answer == "yes":
                user_answer = True
                break
            elif answer == "n" or answer == "no":
                user_answer = False
                break
            elif answer == "?":
                user_answer = "skip"
                break
            else:
                print("Invalid input. Type Y, N, or ?.")

        if user_answer != "skip":
            possible_characters = [
                character for character in possible_characters
                if current_characters[character][best_question] == user_answer
            ]

        if len(possible_characters) == 0:
            print("\nNone of the characters in my database match all your answers.")
            print("I may need more characters in my database Dang It!.")
            break

    if len(possible_characters) == 1:
        guess_answer = input("\nIs your character " + possible_characters[0] + "? (Y/N): ").strip().lower()

        while guess_answer != "y" and guess_answer != "yes" and guess_answer != "n" and guess_answer != "no":
            print("Invalid input. Type Y or N.")
            guess_answer = input("Is your character " + possible_characters[0] + "? (Y/N): ").strip().lower()

        if guess_answer == "y" or guess_answer == "yes":
            print("\nI guessed it! Your character is " + possible_characters[0] + "!")
