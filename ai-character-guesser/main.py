            guess_answer = input("Is your character " + character + "? (Y/N): ").strip().lower()

            while guess_answer != "y" and guess_answer != "yes" and guess_answer != "n" and guess_answer != "no":
                print("Invalid input. Type Y or N.")
                guess_answer = input("Is your character " + character + "? (Y/N): ").strip().lower()

            if guess_answer == "y" or guess_answer == "yes":
                print("\nI guessed it! Your character is " + character + "!")
                win()
                return

